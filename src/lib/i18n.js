export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem("siriusHS_language");

    if (saved && translations[saved]) {
      return saved;
    }
  } catch (error) {
    console.warn("No se pudo leer el idioma guardado:", error);
  }

  return DEFAULT_LANGUAGE;
}

export function saveLanguage(language) {
  if (!translations[language]) {
    return false;
  }

  try {
    localStorage.setItem("siriusHS_language", language);
    return true;
  } catch (error) {
    console.warn("No se pudo guardar el idioma:", error);
    return false;
  }
}

export function getTranslation(language = DEFAULT_LANGUAGE) {
  return translations[language] || translations[DEFAULT_LANGUAGE];
}

// Permite acceder a claves profundas como:
// navigation.home
// dashboard.createEvent
// common.close
export function t(key, language = DEFAULT_LANGUAGE) {
  const dictionary = getTranslation(language);

  const value = key
    .split(".")
    .reduce((current, part) => current?.[part], dictionary);

  if (typeof value === "string") {
    return value;
  }

  // Si una traducción todavía no existe, devolvemos la clave.
  return key;
}

// Dirección de escritura.
// Árabe necesita RTL; los demás idiomas usan LTR.
export function ion(language) {
  return language === "ar" ? "rtl" : "ltr";
}










